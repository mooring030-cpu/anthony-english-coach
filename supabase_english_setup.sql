-- 0) 기존 일본어 앱의 신규 사용자 트리거가 영어 계정까지 잡지 않도록 예외 처리
--    기존 일본어 앱 계정 생성 동작은 그대로 유지됩니다.
create or replace function public.handle_new_user()
returns trigger
language plpgsql
security definer
set search_path = public
as $$
declare
  v_username text;
  v_name text;
  v_role text := 'user';
begin
  if lower(coalesce(new.email,'')) like '%@daco-en.invalid' then
    return new;
  end if;
  v_username := lower(coalesce(new.raw_user_meta_data->>'username', split_part(new.email,'@',1)));
  v_name := coalesce(new.raw_user_meta_data->>'display_name', v_username);
  if v_username !~ '^[a-z0-9_]{3,20}$' then raise exception 'invalid username'; end if;
  if v_username='admin' then
    if exists(select 1 from public.profiles) then raise exception 'admin username is reserved'; end if;
    v_role := 'admin';
  end if;
  insert into public.profiles(user_id,username,display_name,role)
  values(new.id,v_username,v_name,v_role);
  return new;
end;
$$;

-- 1) 영어 전용 테이블
create table if not exists public.english_profiles (
  user_id uuid primary key references auth.users(id) on delete cascade,
  username text not null unique,
  display_name text,
  role text not null default 'user' check (role in ('user','admin')),
  active boolean not null default true,
  created_at timestamptz not null default now(),
  last_login timestamptz
);

create table if not exists public.english_learning_progress (
  user_id uuid primary key references auth.users(id) on delete cascade,
  state jsonb not null default '{}'::jsonb,
  updated_at timestamptz not null default now()
);

create table if not exists public.english_leaderboard (
  user_id uuid primary key references auth.users(id) on delete cascade,
  username text not null,
  display_name text,
  score integer not null default 0,
  total_sessions integer not null default 0,
  learned integer not null default 0,
  streak integer not null default 0,
  attendance_days integer not null default 0,
  first_accuracy numeric(5,2) not null default 0,
  last_study date,
  updated_at timestamptz not null default now()
);

create table if not exists public.english_push_subscriptions (
  id bigint generated by default as identity primary key,
  user_id uuid not null references auth.users(id) on delete cascade,
  endpoint text not null unique,
  p256dh text not null,
  auth text not null,
  timezone text not null default 'Asia/Seoul',
  enabled boolean not null default true,
  created_at timestamptz not null default now(),
  updated_at timestamptz not null default now()
);

create index if not exists english_profiles_username_idx on public.english_profiles(username);
create index if not exists english_progress_updated_idx on public.english_learning_progress(updated_at desc);
create index if not exists english_leaderboard_score_idx on public.english_leaderboard(score desc, updated_at asc);
create index if not exists english_push_user_idx on public.english_push_subscriptions(user_id);

-- 2) 영어 앱 신규 사용자 생성 트리거
create or replace function public.english_handle_new_user()
returns trigger
language plpgsql
security definer
set search_path = public
as $$
declare
  v_username text;
  v_name text;
  v_role text := 'user';
begin
  if lower(coalesce(new.email,'')) not like '%@daco-en.invalid' then
    return new;
  end if;
  v_username := lower(coalesce(new.raw_user_meta_data->>'username', split_part(new.email,'@',1)));
  v_name := coalesce(new.raw_user_meta_data->>'display_name', v_username);
  if v_username !~ '^[a-z0-9_]{3,20}$' then raise exception 'invalid username'; end if;
  if v_username='admin' then
    if exists(select 1 from public.english_profiles) then raise exception 'admin username is reserved'; end if;
    v_role := 'admin';
