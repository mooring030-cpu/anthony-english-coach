drop trigger if exists on_auth_english_user_created on auth.users;
create trigger on_auth_english_user_created
after insert on auth.users
for each row execute procedure public.english_handle_new_user();

-- 3) 영어 앱 관리자 판정 / 최근 로그인
create or replace function public.english_is_admin()
returns boolean language sql stable security definer set search_path=public as $$
  select exists(select 1 from public.english_profiles where user_id=(select auth.uid()) and role='admin' and active=true);
$$;

create or replace function public.english_touch_last_login()
returns void language sql security definer set search_path=public as $$
  update public.english_profiles set last_login=now() where user_id=(select auth.uid()) and active=true;
$$;

revoke all on function public.english_is_admin() from public;
revoke all on function public.english_touch_last_login() from public;
grant execute on function public.english_is_admin() to authenticated;
grant execute on function public.english_touch_last_login() to authenticated;

